import pandas as pd


# =====================================================
# DATAPULSE — INSIGHTAI ENGINE
# =====================================================

def get_numeric_column(df, column):
    """
    Safely convert a dataset column into numeric values.
    Invalid and missing values are ignored.
    """
    if column not in df.columns:
        return None

    return pd.to_numeric(df[column], errors="coerce").dropna()


# =====================================================
# 01. GENERATE DATA INSIGHTS
# =====================================================

def generate_insights(df):

    insights = []

    if df is None or df.empty:
        return [{
            "title": "Dataset Status",
            "value": "No Data",
            "description": "Upload a dataset containing valid records."
        }]

    # -------------------------------------------------
    # REVENUE ANALYSIS
    # -------------------------------------------------

    revenue = get_numeric_column(df, "Revenue")

    if revenue is not None and not revenue.empty:

        total_revenue = revenue.sum()
        average_revenue = revenue.mean()

        insights.append({
            "title": "Total Revenue",
            "value": f"{total_revenue:,.2f}",
            "description": "Total revenue generated by all available records."
        })

        insights.append({
            "title": "Average Order Revenue",
            "value": f"{average_revenue:,.2f}",
            "description": "Average revenue generated per valid record."
        })

    # -------------------------------------------------
    # PROFIT ANALYSIS
    # -------------------------------------------------

    profit = get_numeric_column(df, "Profit")

    if profit is not None and not profit.empty:

        total_profit = profit.sum()

        insights.append({
            "title": "Total Profit",
            "value": f"{total_profit:,.2f}",
            "description": "Overall profit generated by the dataset."
        })

        if "Product" in df.columns:

            product_data = pd.DataFrame({
                "Product": df["Product"],
                "Profit": pd.to_numeric(
                    df["Profit"], errors="coerce"
                )
            }).dropna()

            if not product_data.empty:

                product_profit = product_data.groupby(
                    "Product"
                )["Profit"].sum()

                if not product_profit.empty:

                    best_product = product_profit.idxmax()

                    insights.append({
                        "title": "Most Profitable Product",
                        "value": str(best_product),
                        "description": (
                            f"Profit generated: "
                            f"{product_profit.max():,.2f}"
                        )
                    })

    # -------------------------------------------------
    # PRODUCT REVENUE ANALYSIS
    # -------------------------------------------------

    if "Product" in df.columns and revenue is not None:

        product_data = pd.DataFrame({
            "Product": df["Product"],
            "Revenue": pd.to_numeric(
                df["Revenue"], errors="coerce"
            )
        }).dropna()

        if not product_data.empty:

            product_revenue = product_data.groupby(
                "Product"
            )["Revenue"].sum()

            if not product_revenue.empty:

                best_product = product_revenue.idxmax()

                insights.append({
                    "title": "Top Revenue Product",
                    "value": str(best_product),
                    "description": (
                        f"Revenue generated: "
                        f"{product_revenue.max():,.2f}"
                    )
                })

    # -------------------------------------------------
    # REGION ANALYSIS
    # -------------------------------------------------

    if "Region" in df.columns and revenue is not None:

        region_data = pd.DataFrame({
            "Region": df["Region"],
            "Revenue": pd.to_numeric(
                df["Revenue"], errors="coerce"
            )
        }).dropna()

        if not region_data.empty:

            region_revenue = region_data.groupby(
                "Region"
            )["Revenue"].sum()

            if not region_revenue.empty:

                best_region = region_revenue.idxmax()

                insights.append({
                    "title": "Best Performing Region",
                    "value": str(best_region),
                    "description": (
                        f"Revenue generated: "
                        f"{region_revenue.max():,.2f}"
                    )
                })

    # -------------------------------------------------
    # QUANTITY ANALYSIS
    # -------------------------------------------------

    quantity = get_numeric_column(df, "Quantity")

    if quantity is not None and not quantity.empty:

        insights.append({
            "title": "Total Units Sold",
            "value": f"{quantity.sum():,.0f}",
            "description": "Total quantity sold across valid records."
        })

    # -------------------------------------------------
    # DATA QUALITY ANALYSIS
    # -------------------------------------------------

    missing = int(df.isnull().sum().sum())
    duplicates = int(df.duplicated().sum())

    quality = (
        "Good"
        if missing == 0 and duplicates == 0
        else "Needs Attention"
    )

    insights.append({
        "title": "Data Quality",
        "value": quality,
        "description": (
            f"{missing} missing values and "
            f"{duplicates} duplicate rows found."
        )
    })

    return insights


# =====================================================
# 02. GENERATE SMART RECOMMENDATIONS
# =====================================================

def generate_recommendations(df):

    recommendations = []

    if df is None or df.empty:

        return [
            "Upload a valid dataset to receive smart recommendations."
        ]

    # -------------------------------------------------
    # PRODUCT PERFORMANCE
    # -------------------------------------------------

    if "Product" in df.columns and "Revenue" in df.columns:

        product_data = pd.DataFrame({
            "Product": df["Product"],
            "Revenue": pd.to_numeric(
                df["Revenue"], errors="coerce"
            )
        }).dropna()

        if not product_data.empty:

            product_sales = product_data.groupby(
                "Product"
            )["Revenue"].sum()

            if len(product_sales) > 1:

                best = product_sales.idxmax()
                lowest = product_sales.idxmin()

                recommendations.append(
                    f"Promote {best}, as it generates the "
                    f"highest revenue of {product_sales.max():,.2f}."
                )

                recommendations.append(
                    f"Review the sales strategy of {lowest}, "
                    f"which generates the lowest revenue of "
                    f"{product_sales.min():,.2f}."
                )

    # -------------------------------------------------
    # REGION PERFORMANCE
    # -------------------------------------------------

    if "Region" in df.columns and "Revenue" in df.columns:

        region_data = pd.DataFrame({
            "Region": df["Region"],
            "Revenue": pd.to_numeric(
                df["Revenue"], errors="coerce"
            )
        }).dropna()

        if not region_data.empty:

            region_sales = region_data.groupby(
                "Region"
            )["Revenue"].sum()

            if len(region_sales) > 1:

                best_region = region_sales.idxmax()

                recommendations.append(
                    f"Study the successful sales strategy in "
                    f"{best_region} to identify opportunities "
                    f"for other regions."
                )

    # -------------------------------------------------
    # PROFIT MARGIN
    # -------------------------------------------------

    if "Profit" in df.columns and "Revenue" in df.columns:

        revenue = get_numeric_column(df, "Revenue")
        profit = get_numeric_column(df, "Profit")

        if not revenue.empty and not profit.empty:

            total_revenue = revenue.sum()
            total_profit = profit.sum()

            if total_revenue > 0:

                margin = (total_profit / total_revenue) * 100

                recommendations.append(
                    f"Your overall profit margin is "
                    f"{margin:.2f}%. Monitor this metric "
                    f"to improve business profitability."
                )

    # -------------------------------------------------
    # DATA QUALITY RECOMMENDATION
    # -------------------------------------------------

    missing = int(df.isnull().sum().sum())
    duplicates = int(df.duplicated().sum())

    if missing > 0 or duplicates > 0:

        recommendations.append(
            f"Improve dataset quality by reviewing "
            f"{missing} missing values and "
            f"{duplicates} duplicate rows."
        )

    # -------------------------------------------------
    # FALLBACK
    # -------------------------------------------------

    if not recommendations:

        recommendations.append(
            "Your dataset has been analysed. "
            "Add Product, Revenue, Profit or Region columns "
            "for more detailed business recommendations."
        )

    return recommendations